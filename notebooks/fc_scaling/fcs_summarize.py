"""RESULTS.md for the cohort-size scaling analysis, from the saved predictions (no fitting).
    uv run notebooks/fc_scaling/fcs_summarize.py"""
import json
import os
from pathlib import Path

import numpy as np
import pandas as pd
from dotenv import find_dotenv, load_dotenv

load_dotenv(find_dotenv(usecwd=True))
D = Path(os.environ["DATA_DIRECTORY"]) / "intermed/fc_scaling"
HERE = Path(__file__).resolve().parent
O = HERE / "outputs"
O.mkdir(exist_ok=True)
PTS = ["901", "903", "905", "906", "907", "908"]
meta = json.load(open(D / "meta.json"))
SST = meta["sst"]
rd = lambda n: pd.read_csv(D / n, dtype={"pt": str, "cohort": str})
S1, S2, S3, S4 = rd("s1_scaling.csv.gz"), rd("s2_calibration.csv.gz"), rd("s3_history.csv.gz"), rd("s4_robustness.csv.gz")
S1["cohort"] = S1.cohort.fillna("none")          # an empty cohort is read back as missing
G, NS = pd.read_csv(D / "null_gain_k5.csv"), pd.read_csv(D / "null_scaling_primary.csv")
PRIMARY = "primary: FOOOF, baseline-normalised"
CONDS = list(S1.cond.unique())
f = lambda x, d=3: "—" if x is None or pd.isna(x) else f"{x:.{d}f}"
sg = lambda x, d=3: "—" if pd.isna(x) else f"{x:+.{d}f}"
pf = lambda x: "—" if pd.isna(x) else f"{x:.3f}"
NAME = {"H0": "last value", "H1": "running mean", "H2": "weighted mean of past", "H3": "elastic net on past two values + time", "M1": "time only",
        "M2": "recordings only", "M3": "recordings + time (primary)", "M3h": "recordings + time + past two values"}


def curve(P):
    P = P.assign(se=(P.y - P.pred) ** 2)
    e = P.groupby(["model", "k", "pt", "cohort"]).se.sum().groupby(["model", "k", "pt"]).mean().groupby(["model", "k"]).sum()
    return (1 - e / SST).unstack("k")


def pooled(P):
    return 1 - ((P.y - P.pred) ** 2).sum() / SST


def stats(P):
    y, p = P.y.values, P.pred.values
    return dict(R2=1 - ((y - p) ** 2).sum() / ((y - y.mean()) ** 2).sum(), r=np.corrcoef(y, p)[0, 1] if np.std(p) > 0 else np.nan, MAE=np.abs(y - p).mean(), n=len(y))


L = ["# Cohort-initialised, patient-calibrated next-week prediction: results", "", "<!-- ai-start -->",
     "Generated by `fcs_summarize.py`. Protocol: `PROTOCOL.md` (committed before code and results).",
     f"Every pooled R² uses the same {meta['n_test']} test points (weeks C03–C24, six patients) and one total sum of squares.",
     "The primary condition was selected in an earlier branch after looking at results, so its headline value is not a new test; the questions here are about cohort size, history and calibration.", "",
     "## S1: does prediction improve with the number of other patients in the cohort?", "",
     "Pooled R² by cohort size (0 = the patient's own history only; 5 = all other patients). Each patient's error is averaged over every cohort of that size.", ""]
curves = {}
for c in CONDS:
    cv = curve(S1[S1.cond == c])
    curves[c] = cv
    L += [f"**{c}**", "", "| Model | " + " | ".join(str(k) for k in cv.columns) + " |", "|---|" + "---|" * cv.shape[1]]
    L += [f"| {NAME[m]} | " + " | ".join(f(v) for v in cv.loc[m].values) + " |" for m in ("M1", "M2", "M3")]
    L += ["| recordings + time minus time only | " + " | ".join(sg(v) for v in (cv.loc["M3"] - cv.loc["M1"]).values) + " |", ""]
cp = curves[PRIMARY]
k = np.arange(6)
slope = lambda v: float(np.polyfit(k, v, 1)[0])
nsl = NS[NS.model == "M3"].pivot(index="draw", columns="k", values="R2")
null_slopes = np.array([slope(r.values) for _, r in nsl.iterrows()])
obs_slope, obs_gain50 = slope(cp.loc["M3"].values), float(cp.loc["M3", 5] - cp.loc["M3", 0])
null_gain50 = (nsl[5] - nsl[0]).values
p_slope = (1 + (null_slopes >= obs_slope).sum()) / (1 + len(null_slopes))
p_50 = (1 + (null_gain50 >= obs_gain50).sum()) / (1 + len(null_gain50))
L += ["Null (neural features shifted against everything else), primary condition, recordings + time:", "",
      "| Quantity | observed | null mean | null 95th pct | p |", "|---|---|---|---|---|",
      f"| slope of R² per added patient (H-F1) | {sg(obs_slope, 4)} | {sg(null_slopes.mean(), 4)} | {sg(np.percentile(null_slopes, 95), 4)} | {pf(p_slope)} |",
      f"| R² with five others minus own history only (H-F2) | {sg(obs_gain50)} | {sg(null_gain50.mean())} | {sg(np.percentile(null_gain50, 95))} | {pf(p_50)} |",
      "", f"Slope of the time-only model, for comparison: {sg(slope(cp.loc['M1'].values), 4)} per added patient.", "",
      "Null curve (mean pooled R² by cohort size): " + ", ".join(f"{kk}: {f(v)}" for kk, v in nsl.mean().items()) + ".", ""]
# per patient at k = 0 and 5
P = S1[(S1.cond == PRIMARY) & S1.model.isin(["M1", "M3"])].assign(se=lambda x: (x.y - x.pred) ** 2)
pp = P.groupby(["model", "k", "pt", "cohort"]).se.sum().groupby(["model", "k", "pt"]).mean().unstack("pt")
sstp = P[(P.model == "M3") & (P.k == 5)].groupby("pt").apply(lambda g: ((g.y - g.y.mean()) ** 2).sum())
L += ["Per patient, primary condition: squared error over the 22 test weeks (lower is better; the last row is that patient's own total variance).", "",
      "| Model, cohort size | " + " | ".join(PTS) + " |", "|---|" + "---|" * len(PTS)]
for m in ("M1", "M3"):
    for kk in (0, 5):
        L.append(f"| {NAME[m]}, {kk} others | " + " | ".join(f(pp.loc[(m, kk), p]) for p in PTS) + " |")
L += ["| patient's own total variance | " + " | ".join(f(sstp[p]) for p in PTS) + " |", ""]
# effect of removing each cohort member (k=4 vs k=5), M3 primary
q5 = P[(P.model == "M3") & (P.k == 5)].groupby("pt").se.sum()
q4 = P[(P.model == "M3") & (P.k == 4)]
rem = []
for qd in PTS:
    d = 0.0
    for p in PTS:
        if p == qd:
            continue
        g = q4[(q4.pt == p) & ~q4.cohort.str.split(",").map(lambda c: qd in c)]
        d += g.se.sum() - q5[p]
    rem.append((qd, -d / SST))
L += ["Effect on pooled R² (other five patients' predictions) of removing one member from the cohort, recordings + time:", "",
      "| Removed from cohort | " + " | ".join(a for a, _ in rem) + " |", "|---|" + "---|" * len(rem), "| change in R² | " + " | ".join(sg(b) for _, b in rem) + " |", ""]

L += ["## S2: how many of the patient's own weeks are needed?", "",
      "Cohort of five plus the patient's first N weeks; scored on weeks C17–C24 (48 points). R² about the mean of those points.", ""]
for c in CONDS:
    g = S2[S2.cond == c]
    Ns = sorted(g.N.unique())
    L += [f"**{c}**", "", "| Model | " + " | ".join(f"N = {n}" for n in Ns) + " |", "|---|" + "---|" * len(Ns)]
    for m in ("H0", "M1", "M3"):
        L.append(f"| {NAME[m]} | " + " | ".join(f(stats(g[(g.model == m) & (g.N == n)])["R2"]) if len(g[(g.model == m) & (g.N == n)]) else "—" for n in Ns) + " |")
    L.append("")

L += ["## S3: do the recordings add anything beyond clinical history?", "", "Full cohort (five others plus own earlier weeks).", ""]
tests = []
for c in CONDS:
    for tgt, tn in (("T-raw", "raw weekly nHDRS"), ("T-smooth", "3-week smoothed nHDRS")):
        g = S3[(S3.cond == c) & (S3.target == tgt)]
        L += [f"**{c}, {tn}**", "", "| Model | uses recordings | R² | r | MAE |", "|---|---|---|---|---|"]
        for m in ("H0", "H1", "H2", "H3", "M1", "M3", "M3h"):
            s = stats(g[g.model == m])
            L.append(f"| {NAME[m]} | {'yes' if m in ('M3', 'M3h') else 'no'} | {f(s['R2'])} | {f(s['r'])} | {f(s['MAE'])} |")
        L.append("")
    g = S3[(S3.cond == c) & (S3.target == "T-raw")]
    r2 = {m: pooled(g[g.model == m]) for m in ("M1", "M3", "H3", "M3h")}
    n = G[G.cond == c]
    for nm, a, b in (("H-F3: recordings + time minus time only", "M3", "M1"), ("H-F4: with recordings minus history-only model", "M3h", "H3")):
        obs, nul = r2[a] - r2[b], n[a].values - r2[b]
        tests.append((c, nm, obs, nul.mean(), np.percentile(nul, 95), (1 + (nul >= obs).sum()) / (1 + len(nul))))
L += ["Null (neural features shifted), raw weekly nHDRS, full cohort:", "", "| Condition | Test | observed gain in R² | null mean | null 95th pct | p |", "|---|---|---|---|---|---|"]
L += [f"| {c} | {nm} | {sg(o)} | {sg(a)} | {sg(b)} | {pf(p)} |" for c, nm, o, a, b, p in tests]

L += ["", "## S4: robustness (primary features, full cohort, raw weekly nHDRS)", "", "| Variant | Model | R² | r | MAE |", "|---|---|---|---|---|"]
ref = S3[(S3.cond == PRIMARY) & (S3.target == "T-raw")]
for vn, g in [("reference (all daytime recordings)", ref)] + [(v, S4[S4.variant == v]) for v in S4.variant.unique()]:
    for m in ("M1", "H3", "M3", "M3h"):
        s = stats(g[g.model == m])
        L.append(f"| {vn} | {NAME[m]} | {f(1 - ((g[g.model == m].y - g[g.model == m].pred) ** 2).sum() / SST)} | {f(s['r'])} | {f(s['MAE'])} |")

g5 = ref[ref.pt == "905"]
L += ["", "## S5: the relapse patient (905), weeks C03–C24", "", "| Model | r | MAE | R² within 905 |", "|---|---|---|---|"]
for m in ("H0", "H1", "H3", "M1", "M3", "M3h"):
    s = stats(g5[g5.model == m])
    L.append(f"| {NAME[m]} | {f(s['r'])} | {f(s['MAE'])} | {f(s['R2'])} |")
tp = {(c, nm): p for c, nm, o, a, b, p in tests}
L += ["", "## Hypotheses (primary condition)", "",
      f"- **H-F1** (R² rises with cohort size, beyond the null): slope {sg(obs_slope, 4)} per patient, p = {pf(p_slope)} → " + ("**supported**" if obs_slope > 0 and p_slope < 0.05 else "**not supported**"),
      f"- **H-F2** (cohort of five beats own history only): gain {sg(obs_gain50)}, p = {pf(p_50)} → " + ("**supported**" if obs_gain50 > 0 and p_50 < 0.05 else "**not supported**"),
      "- **H-F3** (recordings add to a time model): " + "; ".join(f"{c.split(':')[0] if ':' in c else c}: gain {sg(o)}, p = {pf(p)}" for c, nm, o, a, b, p in tests if nm.startswith("H-F3")),
      "- **H-F4** (recordings add to clinical history): " + "; ".join(f"{c.split(':')[0] if ':' in c else c}: gain {sg(o)}, p = {pf(p)}" for c, nm, o, a, b, p in tests if nm.startswith("H-F4")),
      "", "<!-- ai-end -->", ""]
(HERE / "RESULTS.md").write_text("\n".join(L))
print("\n".join(L[6:]))
